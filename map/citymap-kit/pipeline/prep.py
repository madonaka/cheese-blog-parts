def centroid(g):
    if not g:
        return None, None
    return (sum(p["lat"] for p in g) / len(g), sum(p["lon"] for p in g) / len(g))


index = {}
for f in ("poi.json", "poi2.json", "allnamed.json", "wide_adm.json", "diplo.json",
          "guest.json", "guest2.json"):
    for e in json.load(open(f, encoding="utf-8"))["elements"]:
        t = e.get("tags", {})
        n = t.get("name")
        if not n:
            continue
        if e["type"] == "node":
            la, lo = e.get("lat"), e.get("lon")
        else:
            c = e.get("center")
            if c and c.get("lat"):
                la, lo = c["lat"], c["lon"]
            elif e.get("geometry"):
                la, lo = centroid(e["geometry"])
            else:
                gs = [m["geometry"] for m in e.get("members", [])
                      if m.get("role") in ("outer", "") and m.get("geometry")]
                la, lo = centroid([p for g in gs for p in g]) if gs else (None, None)
        if la is None:
            continue
        p = PREFER.get(n)
        d = ((la - p[0]) ** 2 + (lo - p[1]) ** 2) ** 0.5 if p else 0.0
        index.setdefault(n, []).append(
            dict(name=n, lat=la, lon=lo, type=e["type"], id=e["id"],
                 rank={"relation": 2, "way": 2, "node": 1}[e["type"]], _d=d))

out, missing, seen = [], [], set()
for cat, tier, n in PICKS:
    if n in seen:
        continue
    seen.add(n)
    if n not in index:
        missing.append(n)
        continue
    r = sorted(index[n], key=lambda x: (-x["rank"], x["_d"]))[0]
    r.pop("_d")
    r["cat"], r["tier"], r["label"] = cat, tier, LABEL.get(n, n)
    r["detail"] = DETAIL.get(n)
    out.append(r)

json.dump(out, open("landmarks.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
io.open("missing.txt", "w", encoding="utf-8").write("\n".join(missing))

