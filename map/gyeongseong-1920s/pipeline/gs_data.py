"""1920년대 경성 — 지도에 실을 것들.

이 파일에 **좌표를 손으로 적지 않는다.** 전부 anchor(지금 실재하는 것) 이름을 적고
anchor_cache.json(= OSM 실측)에서 끌어온다. 못 찾으면 좌표 없이 남아 안 그려지고
audit.py 가 "빠졌다"고 보고한다.

각 항목의 뜻
  name        1920년대 당시 표기 (이 판의 표기 정책)
  anchor      좌표를 얻을 현재 이름.  dong= 을 쓰면 법정동 점으로 떨어지고 근거가 낮아진다
  coord_basis 현존건물 / 터 / 현 지명 대응
  confidence  high(현존 건물·유구) / medium(터가 특정됨) / low(동 수준)
              → low 는 지도에서 빈 기호 + 이름 끝 가운뎃점
  tier        1 = 색 박스 / 2 = 기호+이름 / 3 = 확대 도엽에만
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
_CP = os.path.join(DATA, "anchor_cache.json")
CACHE = json.load(open(_CP, encoding="utf-8")) if os.path.exists(_CP) else {}

# 이름이 같은 후보가 여럿이라 자동 순위로 못 고르는 것들 — 사람이 못 박는다
OVERRIDE = {
    "광화문": ("building", "gatehouse"),
    "숭례문": ("historic", "city_gate"),
    "흥인지문": ("historic", "city_gate"),
    "광희문": ("historic", "city_gate"),
}

# 법정동 점(place=quarter) — 건물 앵커가 없을 때 쓰는 최후 수단
_DONG = {}
for _f in ("dong_pt", "dong"):
    _p = os.path.join(DATA, _f + ".json")
    if not os.path.exists(_p):
        continue
    for _e in json.load(open(_p, encoding="utf-8"))["elements"]:
        _n = _e.get("tags", {}).get("name")
        if not _n or _n in _DONG:
            continue
        if _e.get("lat") is not None:
            _DONG[_n] = (_e["lat"], _e["lon"])
        else:
            _g = [p for m in _e.get("members", []) for p in (m.get("geometry") or [])]
            if _g:
                _DONG[_n] = (sum(p["lat"] for p in _g) / len(_g),
                             sum(p["lon"] for p in _g) / len(_g))


def xy(anchor):
    c = CACHE.get(anchor) or []
    if not c:
        return None, None
    wt = OVERRIDE.get(anchor)
    if wt:
        for r in c:
            if r["tags"].get(wt[0]) == wt[1]:
                return r["lat"], r["lon"]
    return c[0]["lat"], c[0]["lon"]


# ── 1922년 «경성도»에서 직접 읽은 자리 ─────────────────────────
# 도판을 도곽 눈금으로 좌표에 맞춘 뒤(gref.py), 그 위에서 시설을 찍어 얻은 값.
# 검증: 숭례문 오차 28 m, 흥인지문 14 m. 그리고 도판에서 읽은 자리를 현재
# 앵커와 대보니 지방법원 20 m, YMCA 15 m, 보신각 40 m 로 맞았다.
# **이건 현재 지물에 기댄 값이 아니라 1922년 도판 자체에서 나온 값이다.**
PLATE = {
    #  이름            도판 픽셀      →  좌표
    "종로경찰서":        (5261, 4214, 37.57105, 126.98497),
    "경성지방법원":      (5023, 4203, 37.57114, 126.98265),
    "중앙기독교청년회관": (5309, 4269, 37.57061, 126.98544),
}


def P(name, cat, tier, **kw):
    """도판에서 읽은 자리로 시설을 놓는다."""
    x, y, la, lo = PLATE[name]
    r = dict(name=name, cat=cat, tier=tier, anchor="«경성도»1922 (%d,%d)" % (x, y),
             coord_basis="도판 판독", confidence="high", lat=la, lon=lo, shape=None)
    r.update(kw)
    return r


def F(name, cat, tier, anchor, confidence, basis="현존건물", **kw):
    """anchor 가 'dong:○○' 면 법정동 점으로 떨어뜨리고 근거를 low 로 낮춘다."""
    if anchor.startswith("dong:"):
        d = anchor[5:]
        la, lo = _DONG.get(d, (None, None))
        confidence, basis = "low", "현 지명 대응(동)"
        if la is None:
            kw.setdefault("why_missing", "법정동 '%s' 를 OSM 에서 못 찾음" % d)
    else:
        la, lo = xy(anchor)
        if la is None:
            kw.setdefault("why_missing", "앵커 '%s' 를 OSM 에서 못 찾음" % anchor)
    r = dict(name=name, cat=cat, tier=tier, anchor=anchor, coord_basis=basis,
             confidence=confidence, lat=la, lon=lo, shape=None)
    r.update(kw)
    return r


